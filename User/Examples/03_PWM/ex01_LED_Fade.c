/**
 * ============================================================
 * ตัวอย่างที่ 1: LED Fade (PWM)
 * ============================================================
 *
 * แผนผังวงจร (Circuit Diagram):
 *
 *     CH32V003                  LED
 *     --------                  ---
 *     PD2 ----/\/\/\---->|---- GND
 *     PWM1_CH1  220 Ohm
 *
 *     ตอขา PD2 ผานตัวตานทาน 220 โอหมไปยังแอโนด LED
 *     ขาแคโทดของ LED ตอลงกราวนด (GND)
 *
 * API ที่ใช้:
 *   PWM_Init(PWM1_CH1, 1000)   // 1kHz
 *   PWM_Start(PWM1_CH1)
 *   PWM_SetDutyCycle(PWM1_CH1, percent)
 *
 * ============================================================
 * ผลลัพธ์ที่คาดหวัง (Expected Results):
 *   LED จะค่อยๆ สว่างขึ้นจาก 0% ถึง 100% (เพิ่มครั้งละ 1%, หน่วง 10ms)
 *   แล้วค่อยๆ ดับลงจาก 100% ถึง 0% สลับไปเรื่อยๆ
 * ============================================================
 * คำเตือน (WARNINGS):
 *   - ต้องเรียก PWM_Start() หลังจาก PWM_Init() เสมอ ไม่เช่นนั้นจะไม่มีสัญญาณ PWM ออกมา!
 *   - ต่อ LED ถูกขั้ว (ขั้วบวกต่อกับตัวต้านทาน)
 *   - ค่าตัวต้านทาน 220 Ohm เหมาะสำหรับ LED ทั่วไปที่ 3.3V
 * ============================================================
 */

#include <SimpleHAL.h>

int main(void)
{
    // เรียกใช้ SystemCoreClockUpdate() เพื่ออัปเดตความถี่ระบบ
    SystemCoreClockUpdate();

    Timer_Init();
    // กำหนดค่าเริ่มต้น PWM ช่อง 1 ที่ PD2 ความถี่ 1000 Hz (1kHz)
    PWM_Init(PWM1_CH1, 1000);

    // เริ่มต้นการทำงาน PWM (ถ้าไม่มีบรรทัดนี้ จะไม่มีสัญญาณออก!)
    PWM_Start(PWM1_CH1);

    // ตัวแปรเก็บค่า Duty Cycle (0-100)
    int duty = 0;

    // ตัวแปรบอกทิศทาง: 1 = เพิ่ม, -1 = ลด
    int direction = 1;

    // วนรอบไม่สิ้นสุด
    while (1)
    {
        // กำหนดค่า Duty Cycle ให้ PWM ช่อง 1
        PWM_SetDutyCycle(PWM1_CH1, duty);

        // รอ 10 มิลลิวินาที
        Delay_Ms(10);

        // ปรับค่า duty ตามทิศทาง
        duty = duty + direction;

        // ถ้า duty ถึง 100 ให้เปลี่ยนเป็นลดลง
        if (duty >= 100)
        {
            direction = -1;
        }

        // ถ้า duty ถึง 0 ให้เปลี่ยนเป็นเพิ่มขึ้น
        if (duty <= 0)
        {
            direction = 1;
        }
    }
}
