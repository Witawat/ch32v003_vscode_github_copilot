/**
 * ============================================================
 * ตัวอยางที่ 1: LED Blink (กระพริบ LED)
 * ============================================================
 *
 * แผนผังวงจร (Circuit Diagram):
 *
 *     CH32V003                  LED
 *     --------                  ---
 *     PC0 ----/\/\/\---->|---- GND
 *            220 Ohm
 *
 *     ตอขา PC0 ผานตัวตานทาน 220 โอหมไปยังขาแอโนดของ LED
 *     ขาแคโทดของ LED ตอลงกราวนด (GND)
 *
 * ============================================================
 * ผลลัพธที่คาดหวัง (Expected Results):
 * - LED ที่ตอที่ PC0 จะกระพริบที่ความถี่ 1Hz
 * - เปด 500ms / ปด 500ms สลับกันไปเรื่อยๆ
 * ============================================================
 * คำเตือน (WARNINGS):
 * - ตองมีตัวตานทานคาจำกัดกระแส (220 Ohm) เสมอ!
 * - CH32V003 จายกระแสไดสูงสุด 8mA ตอ 1 pin
 * - การตอ LED โดยไมมีตัวตานทานจะทำให LED และ MCU เสียหาย
 * - ไมควรดึงกระแสรวมเกิน 120mA จาก VDD
 * ============================================================
 */

#define CH32V003_PACKAGE  PACKAGE_TSSOP20
#include <SimpleHAL.h>   // รวมไลบรารี SimpleHAL ทั้งหมด (GPIO, Delay, USART, ฯลฯ)

int main(void)           // ฟงกชันหลักของโปรแกรม เปนจุดเริ่มตนการทำงาน
{
    SystemCoreClockUpdate();
    Timer_Init();
    pinMode(PC0, PIN_MODE_OUTPUT);  // ตั้งคาขา PC0 ใหเปนโหมดเอาตพุต (output push-pull)
                                    // เพื่อจายกระแสไฟไปยัง LED

    while(1)                 // วนลูปอนันต์ ทำงานซ้ำไปเรื่อยๆ
    {
        digitalWrite(PC0, HIGH);  // เขียนคาลอจิก HIGH (ไฟ 3.3V) ไปที่ขา PC0
                                  // LED จะติด (มีกระแสไหลผาน LED)

        Delay_Ms(500);        // หนวงเวลา 500 มิลลิวินาที (0.5 วินาที)
                              //  LED จะติดคางไว 500ms

        digitalWrite(PC0, LOW);   // เขียนคาลอจิก LOW (ไฟ 0V/GND) ไปที่ขา PC0
                                  // LED จะดับ (ไมมีกระแสไหลผาน LED)

        Delay_Ms(500);        // หนวงเวลา 500 มิลลิวินาที (0.5 วินาที)
                              // LED จะดับคางไว 500ms
    }                        // สิ้นสุด while loop กลับไปทำซ้ำอีกครั้ง
}                            // สิ้นสุดฟงกชัน main
