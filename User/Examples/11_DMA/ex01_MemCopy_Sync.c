/**
 * ============================================================
 * ตัวอย่างที่ 1: คัดลอกหน่วยความจำแบบซิงโครนัส (MemCopy Sync)
 * ============================================================
 *
 * แผนผังวงจร (Circuit Diagram):
 *
 *     CH32V003              USB-Serial
 *     --------              ----------
 *     PD5 (TX) ----------- RX
 *     PD6 (RX) ----------- TX
 *     GND    -------------- GND
 * 
 *     ไม่มีวงจรภายนอกเพิ่มเติม การทดสอบใช้หน่วยความจำภายใน MCU
 *     ใช้ USART สำหรับแสดงผลผ่าน Serial Monitor เท่านั้น
 *
 * ============================================================
 * ผลลัพธ์ที่คาดหวัง (Expected Results):
 * - "MemCopy OK: All bytes match!"
 * - "MemSet OK: All bytes = 0xFF"
 * - แสดงข้อความยืนยันว่าการคัดลอกและการตั้งค่าหน่วยความจำสำเร็จ
 * ============================================================
 * คำเตือน (WARNINGS):
 * - DMA จะเลือก channel อัตโนมัติ (ตัวแรกที่ว่าง) สำหรับการทำ MemCopy/MemSet
 * - สำหรับการคัดลอกข้อมูลขนาดเล็ก (<50 ไบต์) DMA อาจไม่เร็วกว่า CPU
 * - ต้องแน่ใจว่า src และ dst ไม่ทับซ้อนกัน (overlap) เพราะ DMA M2M อาจไม่รองรับ
 * - DMA_MemSet ใช้ DMA ในโหมด M2P (เขียนค่าเดียวกันทั้งหมด)
 * ============================================================
 */

#include <SimpleHAL.h>    // รวมไลบรารี SimpleHAL ทั้งหมด
#include <string.h>       // รวมไลบรารี string.h สำหรับฟังก์ชัน memcmp และ memset

#define BUFFER_SIZE 100   // กำหนดขนาด buffer เท่ากับ 100 ไบต์

int main(void)            // ฟังก์ชันหลัก จุดเริ่มต้นโปรแกรม
{
    SystemCoreClockUpdate(); // อัปเดตค่าความถี่สัญญาณนาฬิกา (จำเป็นทุกครั้ง)

    USART_SimpleInit(BAUD_115200, USART_PINS_DEFAULT); // เริ่มต้น USART ที่ 115200 baud

    uint8_t src[BUFFER_SIZE]; // ต้นทาง: array ขนาด 100 ไบต์
    uint8_t dst[BUFFER_SIZE]; // ปลายทาง: array ขนาด 100 ไบต์

    for (uint16_t i = 0; i < BUFFER_SIZE; i++) // เตรียมข้อมูลต้นทาง
    {
        src[i] = (uint8_t)(i + 1); // เก็บค่า 1 ถึง 100 ลงใน src
    }

    DMA_MemCopy(dst, src, BUFFER_SIZE); // คัดลอกข้อมูล 100 ไบต์จาก src ไป dst ด้วย DMA (blocking)

    uint8_t copy_ok = 1; // ตัวแปรบอกว่าการคัดลอกถูกต้อง (1 = ใช่)
    for (uint16_t i = 0; i < BUFFER_SIZE; i++) // ตรวจสอบทีละไบต์
    {
        if (dst[i] != src[i]) // ถ้าค่าไม่ตรงกัน
        {
            copy_ok = 0;     // ตั้งค่าเป็นผิดพลาด
            break;           // ออกจาก loop ทันที
        }
    }

    if (copy_ok)             // ถ้าคัดลอกถูกต้องทั้งหมด
    {
        USART_Print("MemCopy OK: All bytes match!\r\n"); // พิมพ์ข้อความยืนยัน
    }

    DMA_MemSet(dst, 0xFF, BUFFER_SIZE); // ตั้งค่าหน่วยความจำ dst ทั้ง 100 ไบต์เป็น 0xFF ด้วย DMA

    uint8_t set_ok = 1;      // ตัวแปรบอกว่าการตั้งค่าถูกต้อง (1 = ใช่)
    for (uint16_t i = 0; i < BUFFER_SIZE; i++) // ตรวจสอบทีละไบต์
    {
        if (dst[i] != 0xFF)  // ถ้าค่าไม่ใช่ 0xFF
        {
            set_ok = 0;      // ตั้งค่าเป็นผิดพลาด
            break;           // ออกจาก loop ทันที
        }
    }

    if (set_ok)              // ถ้าตั้งค่าถูกต้องทั้งหมด
    {
        USART_Print("MemSet OK: All bytes = 0xFF\r\n"); // พิมพ์ข้อความยืนยัน
    }

    while (1) { }            // หยุดโปรแกรม ณ จุดนี้ (รออย่างเดียว)
}                            // สิ้นสุดฟังก์ชัน main
